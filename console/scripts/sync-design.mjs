#!/usr/bin/env node
/**
 * Vendors the Yunori client's design system into the console.
 *
 *   node scripts/sync-design.mjs            copy (and adapt) every source below
 *   node scripts/sync-design.mjs --check    exit 1 if any vendored copy drifted
 *                                           (source changed upstream, or the copy
 *                                           was hand-edited) — run this in CI
 *   --from <dir>  /  YUNORI_CLIENT_DIR      the client checkout (default: ../..
 *                                           from console/, i.e. this monorepo)
 *
 * Vendored files are generated, never edited: each starts with a header naming
 * its source path and the source's sha256. The only adaptation is import
 * rewriting — the client's `@/…` alias (→ client src/) becomes a relative path
 * to the vendored copy, and an `@/…` import that isn't vendored fails loudly.
 *
 * Staged plan (docs/YUNORI-MAIL-SERVER-PLAN.md §9.1): this vendoring is the
 * P0–P1 mechanism; P2 replaces it with a shared `@yunori/ui` package.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const CONSOLE_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const VENDOR_DIR = path.join(CONSOLE_DIR, "src/design/vendor");

/**
 * source (relative to the client repo root) → target (relative to console/).
 * The LOOK (colours, fonts, radii, shadows, motion) and the brand mark come
 * from the live product instead — see scripts/sync-yunori-design.mjs, which
 * writes src/design/yunori/tokens.css; public/favicon.svg is yunori.email's.
 * This script vendors only the structural primitives and the base stylesheet.
 *
 * Primitives NOT vendored on purpose: ui/scroll-area, ui/separator, ui/tooltip
 * (unused here — the console scrolls natively and uses `title` hints), and the
 * admin confirm-dialog (the console needs inline error display on 409s, so it
 * has its own `components/confirm.tsx` built from these same primitives).
 */
const FILES = [
  ["src/globals.css", "src/design/vendor/globals.css"],
  ["tailwind.config.ts", "src/design/vendor/tailwind.config.ts"],
  ["src/lib/utils.ts", "src/design/vendor/lib/utils.ts"],
  ["src/components/ui/button.tsx", "src/design/vendor/ui/button.tsx"],
  ["src/components/ui/dialog.tsx", "src/design/vendor/ui/dialog.tsx"],
  ["src/components/ui/dropdown-menu.tsx", "src/design/vendor/ui/dropdown-menu.tsx"],
  ["src/components/ui/input.tsx", "src/design/vendor/ui/input.tsx"],
  ["src/components/ui/label.tsx", "src/design/vendor/ui/label.tsx"],
  ["src/components/ui/switch.tsx", "src/design/vendor/ui/switch.tsx"],
  ["src/components/ui/textarea.tsx", "src/design/vendor/ui/textarea.tsx"],
  ["src/features/admin/components/ui.tsx", "src/design/vendor/admin/ui.tsx"],
  ["src/features/admin/components/data-table.tsx", "src/design/vendor/admin/data-table.tsx"],
];

// ── args ─────────────────────────────────────────────────────────────────────

const args = process.argv.slice(2);
const check = args.includes("--check");
const fromIdx = args.indexOf("--from");
const CLIENT_DIR = path.resolve(
  CONSOLE_DIR,
  fromIdx >= 0 ? args[fromIdx + 1] : process.env.YUNORI_CLIENT_DIR || "../..",
);

if (!existsSync(path.join(CLIENT_DIR, "src/globals.css"))) {
  console.error(
    `sync-design: the Yunori client checkout was not found at ${CLIENT_DIR}\n` +
      "  Pass --from <dir> or set YUNORI_CLIENT_DIR to a checkout of the client repo.",
  );
  process.exit(2);
}

// ── transform ────────────────────────────────────────────────────────────────

/** `@/x/y` (client src/) → vendored target path (console-relative), if vendored. */
const aliasTargets = new Map();
for (const [src, dst] of FILES) {
  if (!src.startsWith("src/") || !/\.(tsx?|css)$/.test(src)) continue;
  aliasTargets.set(`@/${src.slice(4).replace(/\.(tsx?)$/, "")}`, dst.replace(/\.(tsx?)$/, ""));
}

function rewriteImports(code, target, source) {
  return code.replace(/(from\s+|import\s+)(["'])(@\/[^"']+)\2/g, (_m, kw, q, spec) => {
    const mapped = aliasTargets.get(spec);
    if (!mapped) {
      throw new Error(
        `${source} imports "${spec}", which is not vendored. Add it to FILES in scripts/sync-design.mjs.`,
      );
    }
    let rel = path.relative(path.dirname(target), mapped).split(path.sep).join("/");
    if (!rel.startsWith(".")) rel = `./${rel}`;
    return `${kw}${q}${rel}${q}`;
  });
}

function header(source, sha, ext) {
  const lines = [
    "AUTO-GENERATED by scripts/sync-design.mjs — DO NOT EDIT.",
    `Source: ${source} (Yunori client repo) · sha256 ${sha.slice(0, 16)}`,
    "Re-sync: npm run design:sync · CI drift check: npm run design:check",
  ];
  if (ext === ".svg") return `<!-- ${lines.join(" | ")} -->\n`;
  return `/*\n${lines.map((l) => ` * ${l}`).join("\n")}\n */\n`;
}

function build(source, target) {
  const raw = readFileSync(path.join(CLIENT_DIR, source), "utf8");
  const sha = createHash("sha256").update(raw).digest("hex");
  const ext = path.extname(source);
  let body = raw;
  if (ext === ".ts" || ext === ".tsx") body = rewriteImports(raw, target, source);
  if (ext === ".svg") {
    // Keep the root element first so the file stays a valid standalone SVG.
    const i = body.indexOf("<svg");
    return body.slice(0, i) + header(source, sha, ext) + body.slice(i);
  }
  return header(source, sha, ext) + body;
}

// ── run ──────────────────────────────────────────────────────────────────────

const drift = [];
let written = 0;

for (const [source, target] of FILES) {
  const abs = path.join(CONSOLE_DIR, target);
  let next;
  try {
    next = build(source, target);
  } catch (err) {
    console.error(`sync-design: ${err.message}`);
    process.exit(2);
  }
  const current = existsSync(abs) ? readFileSync(abs, "utf8") : null;
  if (current === next) continue;
  if (check) {
    drift.push(current === null ? `missing   ${target}` : `drifted   ${target}  ⇐  ${source}`);
  } else {
    mkdirSync(path.dirname(abs), { recursive: true });
    writeFileSync(abs, next);
    written++;
  }
}

// Anything in the vendor dir that isn't generated is a hand-made file — not allowed.
const expected = new Set(FILES.map(([, t]) => path.join(CONSOLE_DIR, t)));
const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const p = path.join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
if (existsSync(VENDOR_DIR)) {
  for (const f of walk(VENDOR_DIR)) {
    if (!expected.has(f)) drift.push(`unexpected ${path.relative(CONSOLE_DIR, f)} (vendor/ holds generated files only)`);
  }
}

if (check) {
  if (drift.length > 0) {
    console.error("sync-design: vendored design files are out of sync with the Yunori client:\n");
    for (const d of drift) console.error(`  ${d}`);
    console.error("\nRun `npm run design:sync`, review the diff, and commit it.");
    process.exit(1);
  }
  console.log(`sync-design: ${FILES.length} vendored files match the client.`);
} else {
  if (drift.length > 0) for (const d of drift) console.warn(`sync-design: ${d}`);
  console.log(`sync-design: ${written} file(s) updated, ${FILES.length - written} already current.`);
}
