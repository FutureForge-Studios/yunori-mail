#!/usr/bin/env node
/**
 * Pull the design tokens of the live Yunori product (https://yunori.email)
 * into src/design/yunori/tokens.css — the console's colour, type and radius
 * source of truth. The site inlines its compiled CSS; we take the two token
 * blocks verbatim (the light `:root{…}` that defines `--background`, and the
 * `.dark{…}` override) and add the console's font-variable mapping.
 *
 *   node scripts/sync-yunori-design.mjs           # refresh tokens.css
 *   node scripts/sync-yunori-design.mjs --check   # exit 1 if yunori.email drifted
 *   YUNORI_DESIGN_URL=… overrides the source (e.g. a staging deploy)
 *
 * A network failure in --check mode warns and exits 0 (offline CI must not go
 * red because the marketing site is unreachable); pass --strict to fail.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, "../src/design/yunori/tokens.css");
const SOURCE = process.env.YUNORI_DESIGN_URL || "https://yunori.email";
const check = process.argv.includes("--check");
const strict = process.argv.includes("--strict");

function extract(html) {
  const css = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join("\n");
  const root = css.match(/:root\{[^{}]*--background:[^{}]*\}/);
  const dark = css.match(/\.dark\{[^{}]*--background:[^{}]*\}/);
  if (!root || !dark) throw new Error("token blocks not found — did yunori.email change its CSS shape?");
  const pretty = (block) =>
    block
      .replace(/\{/, " {\n  ")
      .replace(/;(?=[^;]*)/g, ";\n  ")
      .replace(/\s*\}$/, "\n}");
  // Theme-level variables that live outside the two token blocks.
  const extra = ["shadow-panel", "shadow-pop", "shadow-whisper", "ease-quiet"]
    .map((name) => {
      const m = css.match(new RegExp(`--${name}:([^;}]+)`));
      return m ? `  --${name}:${m[1].trim()};` : null;
    })
    .filter(Boolean);
  const theme = extra.length ? `\n:root {\n${extra.join("\n")}\n}\n` : "";
  return `${pretty(root[0])}\n\n${pretty(dark[0])}\n${theme}`;
}

function render(tokens) {
  const sha = createHash("sha256").update(tokens).digest("hex").slice(0, 16);
  return `/*
 * GENERATED by scripts/sync-yunori-design.mjs from ${SOURCE} — do not edit by hand.
 * Token blocks copied verbatim from the live Yunori product (sha256:${sha}).
 * Re-run the script to refresh; \`--check\` detects drift.
 */

${tokens}
/* Console mapping: the vendored Tailwind preset reads --font-sans/--font-serif. */
:root {
  --font-sans: var(--font-geist-sans);
  --font-serif: var(--font-instrument-serif);
  --font-mono: var(--font-geist-mono);
}
`;
}

let html;
try {
  const res = await fetch(SOURCE, { headers: { "user-agent": "yunori-mail-console-design-sync" } });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  html = await res.text();
} catch (e) {
  const msg = `sync-yunori-design: could not fetch ${SOURCE} (${e.message})`;
  if (check && !strict) {
    console.warn(`${msg} — skipping drift check.`);
    process.exit(0);
  }
  console.error(msg);
  process.exit(1);
}

const next = render(extract(html));
if (check) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current !== next) {
    console.error("sync-yunori-design: src/design/yunori/tokens.css differs from yunori.email — run the script to update.");
    process.exit(1);
  }
  console.log("sync-yunori-design: tokens match yunori.email.");
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, next);
  console.log(`sync-yunori-design: wrote ${OUT}`);
}
